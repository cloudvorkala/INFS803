/* ---------------------------------------------------------------------------
   Renders a product's cover.

   `coverUrl` is the S3 object URL the API returns (or, in this build, the cover
   generated by tools/build-catalogue.mjs and served from the same bucket as the
   client). If a product has no cover — a brand new one added through /admin
   before an image is uploaded — the component draws a placeholder from the
   title so the grid never has a hole in it.
   --------------------------------------------------------------------------- */

import { useState } from 'react';
import styles from './BookCover.module.css';

/* Same cloth palette the generated covers use, so a placeholder sits happily
   next to real covers rather than looking like an error state. */
const CLOTHS = [
  ['#2F5D45', '#C9A15A'],
  ['#1F3A5F', '#C9A15A'],
  ['#6E2733', '#D9AE7A'],
  ['#7A5C1E', '#F0DBA8'],
  ['#3A4750', '#B9C4CC'],
  ['#4A2E52', '#C9A15A'],
  ['#1D4E4B', '#C9A15A'],
  ['#2A2723', '#C9A15A'],
];

function hash(str) {
  let h = 2166136261;
  for (let i = 0; i < str.length; i += 1) {
    h ^= str.charCodeAt(i);
    h = Math.imul(h, 16777619);
  }
  return Math.abs(h);
}

export default function BookCover({ title, author, coverUrl, size = 'md' }) {
  const [failed, setFailed] = useState(false);

  if (coverUrl && !failed) {
    return (
      <img
        className={`${styles.cover} ${styles[size]}`}
        src={coverUrl}
        alt={`Cover of ${title}`}
        loading="lazy"
        decoding="async"
        width="400"
        height="600"
        onError={() => setFailed(true)}
      />
    );
  }

  const [cloth, foil] = CLOTHS[hash(title || 'book') % CLOTHS.length];

  return (
    <div
      className={`${styles.cover} ${styles.placeholder} ${styles[size]}`}
      style={{ background: cloth, '--foil-stamp': foil }}
      role="img"
      aria-label={`Cover of ${title}`}
    >
      <span className={styles.spine} />
      <span className={styles.rule} />
      <span className={styles.title}>{title}</span>
      {author && <span className={styles.author}>{author}</span>}
    </div>
  );
}
